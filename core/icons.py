FALLBACK_CHARS = {
    "camera": "📷",
    "sun": "☀",
    "moon": "🌙",
    "globe": "🌐",
    "zoom-in": "＋",
    "zoom-out": "－",
    "folder": "📁",
    "folder-open": "📂",
    "rocket": "🚀",
    "x": "✕",
    "trash": "🗑",
    "shield": "🛡",
    "code": "</>",
    "github": "◆",
    "external": "↗",
}

_CACHE: dict = {}


def has_svg_support() -> bool:
    return _SVG_AVAILABLE


def get_icon(name: str, size: int = 16, fg: str = "#000000") -> Tuple[str, object]:
    """
    Returns ("image", PhotoImage) if cairosvg+Pillow available,
    otherwise ("text", unicode_glyph).
    Cached by (name, size, fg).
    """
    if name not in SVG_ICONS:
        return ("text", FALLBACK_CHARS.get(name, "?"))

    if _SVG_AVAILABLE:
        key = (name, size, fg)
        if key not in _CACHE:
            try:
                svg = SVG_ICONS[name].replace("currentColor", fg)
                png = cairosvg.svg2png(
                    bytestring=svg.encode("utf-8"),
                    output_width=size,
                    output_height=size,
                )
                img = Image.open(io.BytesIO(png)).convert("RGBA")
                _CACHE[key] = ImageTk.PhotoImage(img)

            except Exception:
                _CACHE[key] = None

        img = _CACHE.get(key)
        if img is not None:
            return ("image", img)

    return ("text", FALLBACK_CHARS.get(name, "?"))
